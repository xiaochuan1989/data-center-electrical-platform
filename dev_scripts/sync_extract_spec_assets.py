"""Create a browser reference snapshot from the installed extract-spec skill."""
import argparse
import json
import runpy
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--skill-dir', type=Path, default=Path.home() / '.codex/skills/extract-spec')
args = parser.parse_args()
registry = runpy.run_path(str(args.skill_dir / 'scripts/device_registry.py'))['DEVICE_REGISTRY']
prompt = (args.skill_dir / 'scripts/ai_prompt.md').read_text(encoding='utf-8')
match = re.search(r'^# extract-spec v(\d+\.\d+\.\d+)$', (args.skill_dir / 'SKILL.md').read_text(encoding='utf-8'), re.MULTILINE)
if not match:
    raise ValueError('Cannot identify installed skill version')
version = match.group(1)
if f'版本：{version}。' not in prompt:
    raise ValueError('Skill and prompt version mismatch')
target = Path(__file__).resolve().parents[1] / 'src/data/spec-extraction-reference.js'
target.write_text(f'// Generated by dev_scripts/sync_extract_spec_assets.py; extract-spec v{version}.\n'
                  '// Registry and extraction instructions only; no customer data.\n'
                  f'export const SPEC_SKILL_VERSION = "{version}";\n'
                  'export const SPEC_DEVICE_REGISTRY = ' + json.dumps(registry, ensure_ascii=False, indent=2) + ';\n'
                  'export const SPEC_SKILL_PROMPT = ' + json.dumps(prompt, ensure_ascii=False) + ';\n', encoding='utf-8')
print(f'Synced {len(registry)} device types and extraction instructions.')
